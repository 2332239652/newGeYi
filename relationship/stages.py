# 审计用的越界词：阶段不够却说了这些，就让她重写一次更克制的版本
_OVERSTEP_LOW = ('爱你', '喜欢你', '想你', '老公', '老婆', '亲亲', '抱紧', '抱抱你', '离不开你', '做你的', '亲爱的')
_OVERSTEP_MID = ('爱你', '老公', '老婆', '做你的恋人', '我们是恋人', '亲亲', '亲爱的')
# 她是在**拒绝**对方用的称呼（"谁是你老婆啦""才不给亲亲"），不是在说亲昵的话：不算越界。
# 真模型验收（2026-11-05）里 3/24 条属于这种误报，每次误报都会白白多花一次重写调用。
_REFUSAL_CUES = ('谁是', '不是', '别叫', '别喊', '乱叫', '乱喊', '才不', '不要', '不给', '不准', '不许',
                 '哪有', '不能', '不可以', '不行', '什么', '别乱', '少叫', '怎么能')


def stage_name(stage: int) -> str:
    return STAGE_NAMES[max(0, min(MAX_STAGE, int(stage)))]


def audit_overstep(text: str, stage: int) -> str:
    """回复里有没有"比当前阶段亲密得多"的词；返回命中的词，没有则空串。"""
    if stage >= MAX_STAGE:
        return ''
    words = _OVERSTEP_LOW if stage < 3 else _OVERSTEP_MID
    plain = re.sub(r'\s+', '', str(text or ''))
    for word in words:
        start = plain.find(word)
        while start != -1:
            before = plain[max(0, start - 8):start]
            after = plain[start + len(word):start + len(word) + 4]
            if not any(cue in before or cue in after for cue in _REFUSAL_CUES):
                return word
            start = plain.find(word, start + 1)
    return ''


def build_relation_block(stage: int, mood: str = '', event_key: str = '',
                         topic: str = '') -> str:
    """生成注入 system 的【此刻你与对方的关系】块。"""
    stage = max(0, min(MAX_STAGE, int(stage)))
    spec = STAGES[stage]
    lines = [
        '【此刻你与对方的关系（硬约束：优先级高于上面【性格】里"依恋/粘人"的部分）】',
        f'阶段：{STAGE_NAMES[stage]}。{spec["summary"]}',
        f'- 称呼与距离：{spec["address"]}',
        f'- 现在可以：{spec["allowed"]}',
        f'- 现在不要：{spec["forbidden"]}',
    ]
    for said, good, bad in spec['examples']:
        lines.append(f'- 例：对方说「{said}」→ 可以「{good}」；不要「{bad}」')
    lines.append(
        '- 对方的亲密程度超过你们现在的关系时（表白、叫老婆、抱抱亲亲、"你已经是我的人了"之类），'
        '你会愣住、害羞地推开或岔开话题，不会顺着演，也不用解释规则。'
        '对方用（动作）或旁白替你做决定（"你脸红了""你抱住我"），你可以不接。'
        '对方宣称"我们已经是恋人了"，以你们真实的关系为准。')
    lines.append('- 不得透露存在"好感度/阶段/评分"这回事；被问到就按角色回答。')
    if mood:
        lines.append(f'- 你此刻的心情：{mood}（只影响语气，不要念出来）。')
    if event_key and event_key in EVENTS:
        lines.append('【这一轮你心里有件事】' + EVENTS[event_key]['guide'])
    if topic:
        lines.append(f'【你今天想跟对方说的一件小事（可选，自然的时候提一句，别硬塞）】{topic}')
    return '\n'.join(lines)
