def get_random_preset(emotion: str = "日常") -> str:
    """获取指定情绪的一句随机经典台词（缺省回退：日常）。"""
    norm = normalize_emotion(emotion)
    phrases = EMOTION_PRESETS.get(norm, EMOTION_PRESETS["日常"])
    return random.choice(phrases)


def get_random_poke_voice() -> tuple[str, str]:
    """获取戳一戳互动的一句随机彩蛋语音 (emotion, text)。"""
    return random.choice(POKE_VOICE_PRESETS)
